async def seed_data():
    async with AsyncSessionLocal() as session:
        try:
            added_count = 0
            skipped_count = 0

            for item in RAW_DATA:
                audio = item.get("audio")
                assignment = item.get("assignment")
                questions = item.get("questions")

                # Dublikatni aniqlash:
                # Bir xil audio, assignment va questions mazmuni bor-yo'qligini tekshiramiz
                stmt = select(Quest).where(
                    Quest.audio == audio,
                    Quest.assignment == assignment
                )
                result = await session.execute(stmt)
                existing_quests = result.scalars().all()

                # Bir xil savollar to'plami allaqachon mavjudligini tekshirish
                is_duplicate = False
                for existing in existing_quests:
                    # JSON strukturani to'g'ridan-to'g meymiz
                    if existing.questions == questions:
                        is_duplicate = True
                        break

                if is_duplicate:
                    skipped_count += 1
                    print(f"⚠️ Dublikat o'tkazib yuborildi: audio='{audio}'")
                    continue

                # Yangi savolni yaratish va saqlash
                new_quest = Quest(
                    audio=audio,
                    assignment=assignment,
                    questions=questions
                )
                session.add(new_quest)
                added_count += 1

            await session.commit()
            print(f"\n✅ Seeding yakunlandi!")
            print(f"➕ Qo'shildi: {added_count} ta")
            print(f"⏭ O'tkazib yuborildi (dublikat): {skipped_count} ta")

        except Exception as e:
            await session.rollback()
            print(f"❌ Seed qilishda xatolik yuz berdi: {e}")


async def main():
    # Kerak bo'lsa avval jadvallar yaratilishini ta'minlaymiz
    try:
        await init_db()
    except Exception:
        pass
        
    await seed_data()


if __name__ == "__main__":
    asyncio.run(main())